-- 1. Customer Table
CREATE TABLE Customer (
    CustomerID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FirstName        VARCHAR2(50) NOT NULL,
    LastName         VARCHAR2(50) NOT NULL,
    Email            VARCHAR2(100) UNIQUE NOT NULL,
    PhoneNumber      VARCHAR2(20),
    Address          VARCHAR2(255),
    RegistrationDate DATE DEFAULT SYSDATE NOT NULL
);

-- 2. Product Table
CREATE TABLE Product (
    ProductID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name          VARCHAR2(100) NOT NULL,
    Description   VARCHAR2(500),
    Price         NUMBER(10, 2) NOT NULL,
    StockQuantity NUMBER DEFAULT 0 NOT NULL,
    CategoryID    NUMBER
);

-- 3. Shopping_Cart Table
CREATE TABLE Shopping_Cart (
    CartID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CustomerID NUMBER NOT NULL,
    CONSTRAINT fk_cart_customer FOREIGN KEY (CustomerID) 
        REFERENCES Customer(CustomerID)
);

-- 4. Cart_Item Table
CREATE TABLE Cart_Item (
    CartItemID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CartID     NUMBER NOT NULL,
    ProductID  NUMBER NOT NULL,
    Quantity   NUMBER NOT NULL,
    UnitPrice  NUMBER(10, 2) NOT NULL,
    CONSTRAINT fk_cartitem_cart FOREIGN KEY (CartID) 
        REFERENCES Shopping_Cart(CartID) ON DELETE CASCADE,
    CONSTRAINT fk_cartitem_product FOREIGN KEY (ProductID) 
        REFERENCES Product(ProductID)
);

-- 5. Order Table
CREATE TABLE "Order" (
    OrderID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CustomerID  NUMBER NOT NULL,
    OrderDate   DATE DEFAULT SYSDATE NOT NULL,
    TotalAmount NUMBER(10, 2) NOT NULL,
    Status      VARCHAR2(50) DEFAULT 'Pending' NOT NULL,
    CONSTRAINT fk_order_customer FOREIGN KEY (CustomerID) 
        REFERENCES Customer(CustomerID)
);

-- 6. Order_Item Table
CREATE TABLE Order_Item (
    OrderItemID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderID     NUMBER NOT NULL,
    ProductID   NUMBER NOT NULL,
    Quantity    NUMBER NOT NULL,
    UnitPrice   NUMBER(10, 2) NOT NULL,
    CONSTRAINT fk_orderitem_order FOREIGN KEY (OrderID) 
        REFERENCES "Order"(OrderID) ON DELETE CASCADE,
    CONSTRAINT fk_orderitem_product FOREIGN KEY (ProductID) 
        REFERENCES Product(ProductID)
);

-- 7. Payment Table
CREATE TABLE Payment (
    PaymentID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderID       NUMBER NOT NULL,
    Amount        NUMBER(10, 2) NOT NULL,
    PaymentDate   DATE DEFAULT SYSDATE NOT NULL,
    PaymentMethod VARCHAR2(50) NOT NULL,
    CONSTRAINT fk_payment_order FOREIGN KEY (OrderID) 
        REFERENCES "Order"(OrderID) ON DELETE CASCADE
);