CREATE TABLE department (
    department_id NUMBER(10) PRIMARY KEY,
    department_name VARCHAR2(100),
    location VARCHAR2(100),
    phone_extension VARCHAR2(10)
);

CREATE TABLE doctor (
    doctor_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    specialization VARCHAR2(80) NOT NULL,
    license_number VARCHAR2(30) NOT NULL,
    department_id NUMBER(10) NOT NULL,
    CONSTRAINT pk_doctor PRIMARY KEY (doctor_id),
    CONSTRAINT uk_doctor_license UNIQUE (license_number),
    CONSTRAINT fk_doctor_department FOREIGN KEY (department_id)
        REFERENCES department(department_id)
);

CREATE TABLE patient (
    patient_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR2(10) NOT NULL,
    contact_number VARCHAR2(20) NOT NULL,
    address VARCHAR2(255) NOT NULL,
    CONSTRAINT pk_patient PRIMARY KEY (patient_id)
);

CREATE TABLE room (
    room_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    room_number VARCHAR2(20) NOT NULL,
    room_type VARCHAR2(50) NOT NULL,
    daily_rate NUMBER(10, 2) NOT NULL,
    status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    CONSTRAINT pk_room PRIMARY KEY (room_id),
    CONSTRAINT uk_room_number UNIQUE (room_number)
);

CREATE TABLE admission (
    admission_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    patient_id NUMBER(10) NOT NULL,
    doctor_id NUMBER(10) NOT NULL,
    room_id NUMBER(10) NOT NULL,
    admission_date DATE DEFAULT SYSDATE NOT NULL,
    discharge_date DATE,
    diagnosis VARCHAR2(255) NOT NULL,

    CONSTRAINT pk_admission PRIMARY KEY (admission_id),

    CONSTRAINT fk_admission_patient FOREIGN KEY (patient_id)
        REFERENCES patient(patient_id),

    CONSTRAINT fk_admission_doctor FOREIGN KEY (doctor_id)
        REFERENCES doctor(doctor_id),

    CONSTRAINT fk_admission_room FOREIGN KEY (room_id)
        REFERENCES room(room_id)
);

CREATE TABLE building (
    building_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    building_length NUMBER(10) NOT NULL
);
